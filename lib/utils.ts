export function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
}

export function cityStateSlug(city: string, state: string): string {
  return `${slugify(city)}-${state.toLowerCase()}`
}

export function formatPhone(phone: string): string {
  const digits = phone.replace(/\D/g, '')
  if (digits.length === 10) {
    return `(${digits.slice(0, 3)}) ${digits.slice(3, 6)}-${digits.slice(6)}`
  }
  if (digits.length === 11 && digits[0] === '1') {
    return `(${digits.slice(1, 4)}) ${digits.slice(4, 7)}-${digits.slice(7)}`
  }
  return phone
}

export function doctorName(listing: {
  first_name?: string | null
  last_name?: string | null
  business_name?: string | null
}): string {
  if (listing.first_name && listing.last_name) {
    return `Dr. ${listing.first_name} ${listing.last_name}`
  }
  if (listing.business_name) return listing.business_name
  return 'Pain Management Specialist'
}

